let n = 0;
function P(category, title, price, compareAt, description, specs, variants) {
  n += 1;
  const slug = slugify(title);
  return {
    id: 'p' + String(n).padStart(3, '0'),
    slug,
    title,
    category,
    price,
    compareAt: compareAt || null,
    images: [`/art/${category}/${(Math.floor((n - 1) / 4) + n) % 4}.svg`],
    description,
    specs: specs || [],
    variants: (variants || []).map(([name, vprice], i) => ({ id: 'v' + (i + 1), name, price: vprice, sku: '' })),
    featured: n % 4 === 1,
    active: true,
    sample: true,
    supplierUrl: '',
    cjPid: '',
    createdAt: 1760000000000 + n * 1000,
  };
}

